import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { _electron } from 'playwright'

const root=resolve(fileURLToPath(new URL('../',import.meta.url)))
const temp=await mkdtemp(join(tmpdir(),'yanye-writing-ui-'))
const markdown=join(temp,'审阅.md'), source=join(temp,'公式.md'), plain=join(temp,'校对.txt')
const mixed='# 目录\r\n\r\n$$\nx^2 + y^2\n$$\r\n\r\n```mermaid\r\nflowchart LR\r\nA[初稿] --> B[归档]\r\n```\r\n\r\n结语 $x+1$。\r终'
const txt=Buffer.from('\uFEFFb2\r\na\nb2\r末')
const legacy=join(temp,'原编码.txt'),gbCopy=join(temp,'原编码副本.txt'),utfCopy=join(temp,'独立 UTF8.txt')
const oldBytes=Buffer.from('d6d0cec40d0abcc7c2bc','hex')
const largeFile=join(temp,'长稿.md')
const largeRaw='---\r\ntitle: 长稿\r\n---\r\n# 前记\r\n\r\n原句。\n\n$$\rx^2 + y^2\r$$\r\n\r\n```text\n'+
  '本地文本 / reading line\n'.repeat(12500)+'```\r\n\r\n# 终卷\r\n\n原句。'
const errors=[]
let app,page
const button=name=>page.getByRole('button',{name,exact:true})
const label=name=>page.getByLabel(name,{exact:true})
async function open(path) {
  await app.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]})},path)
  await button('打开本地文件').click()
}
async function saveDestination(path) {
  await app.evaluate(({dialog},path)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:path})},path)
}
async function savedBytes(path,expected) {
  // An atomic rename is observable before the renderer receives its save acknowledgement.
  await page.waitForFunction(()=>document.querySelector('button[title^="保存到磁盘"]')?.disabled===false)
  await page.keyboard.press('Control+s')
  await page.getByText('文件已保存到磁盘',{exact:true}).waitFor({timeout:30_000})
  for(let i=0;i<100;i++) {
    const data=await readFile(path)
    if (data.equals(expected)) return
    await new Promise(resolve=>setTimeout(resolve,40))
  }
  assert.deepEqual(await readFile(path),expected)
}
try {
  await Promise.all([writeFile(markdown,'# 文稿\n\n首段**稿件**，稿件。\n\n末段'), writeFile(source,mixed),writeFile(plain,txt),writeFile(legacy,oldBytes),writeFile(largeFile,largeRaw)])
  const exe=process.argv[2] ? resolve(process.argv[2]) : createRequire(import.meta.url)('electron')
  app=await _electron.launch({executablePath:exe,args:process.argv[2]?[]:[root],env:{...process.env,YANYE_PROFILE:join(temp,'profile')}})
  page=await app.firstWindow()
  page.setDefaultTimeout(12000)
  page.on('pageerror',error=>errors.push(error.message))
  await page.context().setOffline(true)

  await open(markdown)
  const rich=label('正文编辑器')
  await rich.click()
  await rich.press('Control+h')
  await label('查找文字').fill('稿件')
  await button('下一处').click()
  assert.equal(await page.evaluate(()=>window.getSelection().toString()),'稿件')
  await page.keyboard.press('F3')
  await page.getByText('2 / 2',{exact:true}).waitFor()
  await label('替换文字').fill('定稿')
  await button('全部替换').click()
  assert.ok((await rich.innerText()).includes('首段定稿，定稿。'))
  await button('关闭查找').click()
  await rich.press('Control+z')
  assert.ok((await rich.innerText()).includes('首段稿件，稿件。'))
  await rich.press('F8')
  await page.locator('.md-focus .md-active-block').first().waitFor()
  await rich.press('F9')
  await page.locator('.md-typewriter').waitFor()
  await rich.press('Control+End')
  await rich.press('Control+3')
  await rich.locator('h3').getByText('末段').waitFor()
  await page.keyboard.press('Control+s')
  for(let n=0;n<100 && !(await readFile(markdown,'utf8')).includes('### 末段');n++) await new Promise(r=>setTimeout(r,40))
  assert.match(await readFile(markdown,'utf8'),/### 末段/)
  await button('返回文件中心').click()

  await open(source)
  const raw=label('Markdown 源码')
  await raw.waitFor()
  await button('写作工具').click()
  await page.getByRole('button',{name:'公式与图表预览'}).click()
  await page.locator('.md-figure-content .katex').waitFor()
  await label('预览对象').selectOption('1')
  await page.waitForFunction(()=>document.querySelector('.md-figure-content img')?.naturalWidth>0)
  await button('关闭预览').click()
  await button('阅读').click()
  const article=label('Markdown 阅读正文')
  await article.locator('h1').getByText('目录').waitFor()
  await article.locator('.md-block-slot .katex').waitFor()
  await article.locator('.md-inline-slot .katex').waitFor()
  await page.waitForFunction(()=>document.querySelector('.md-reading img')?.naturalWidth>0)
  const diagram='flowchart LR\nA[初稿] --> B[归档]'
  await article.getByRole('button',{name:/编辑第 .*行图表源码/}).click()
  assert.equal(await raw.evaluate(el=>el.value.slice(el.selectionStart,el.selectionEnd)),diagram)
  await page.keyboard.insertText(diagram.replace('初稿','校订'))
  await savedBytes(source,Buffer.from(mixed.replace('初稿','校订')))
  await raw.press('Control+z')
  await savedBytes(source,Buffer.from(mixed))
  await button('阅读').click()
  await article.getByRole('button',{name:'编辑第 12 行公式源码'}).click()
  assert.equal(await raw.evaluate(el=>el.value.slice(el.selectionStart,el.selectionEnd)),'x+1')
  await raw.press('Control+h')
  await label('查找文字').fill('结语')
  await label('替换文字').fill('定稿')
  await button('全部替换').click()
  await savedBytes(source,Buffer.from(mixed.replace('结语','定稿')))
  await button('关闭查找').click()
  await raw.press('Control+z')
  await savedBytes(source,Buffer.from(mixed))
  await button('返回文件中心').click()

  await open(plain)
  const content=label('纯文本正文')
  await content.focus()
  await content.press('Control+Home')
  await content.press('Control+F2')
  await content.press('Control+End')
  await content.press('Control+F2')
  await content.press('F2')
  await page.getByText('第 1 行，第 1 列',{exact:true}).waitFor()
  assert.equal(await page.locator('.txt-bookmark').count(),2)
  await button('自动换行').click()
  assert.equal(await button('自动换行').getAttribute('aria-pressed'),'true')
  await button('显示空白').click()
  assert.equal(await button('显示空白').getAttribute('aria-pressed'),'true')
  await label('行操作').selectOption('unique')
  assert.equal(await page.locator('.cm-content .cm-line').allTextContents().then(v=>v.join('\n')),'b2\na\n末')
  await button('撤销').click()
  assert.equal(await label('行尾格式').inputValue(),'mixed')
  await label('行尾格式').selectOption('n')
  await label('保存编码').selectOption('utf16le')
  await savedBytes(plain,Buffer.from('\uFEFFb2\na\nb2\n末','utf16le'))
  await button('撤销').click()
  await button('撤销').click()
  assert.equal(await label('行尾格式').inputValue(),'mixed')
  await savedBytes(plain,txt)
  await button('返回文件中心').click()
  await open(legacy)
  await page.getByLabel('文件编码').selectOption('gbk')
  await button('按此编码打开').click()
  await content.press('Control+End')
  await page.keyboard.insertText('新')
  const edited=Buffer.concat([oldBytes,Buffer.from('d0c2','hex')])
  await savedBytes(legacy,edited)
  await saveDestination(gbCopy)
  await button('另存为').click()
  await button(basename(gbCopy)).first().waitFor()
  assert.deepEqual(await readFile(gbCopy),edited)
  await content.press('Control+End')
  await page.keyboard.insertText('😀')
  await page.keyboard.press('Control+s')
  await page.getByText(/U\+1F600/).waitFor()
  await button('返回编辑').click()
  assert.deepEqual(await readFile(gbCopy),edited)
  await saveDestination(gbCopy)
  await page.keyboard.press('Control+s')
  await button('另存 UTF-8 副本').click()
  await button('关闭文件错误').waitFor()
  assert.deepEqual(await readFile(gbCopy),edited)
  await button('关闭文件错误').click()
  await saveDestination(utfCopy)
  await page.keyboard.press('Control+s')
  await button('另存 UTF-8 副本').click()
  await button(basename(utfCopy)).first().waitFor()
  assert.deepEqual(await readFile(utfCopy),Buffer.from('中文\r\n记录新😀'))
  assert.deepEqual(await readFile(legacy),edited)
  assert.deepEqual(await readFile(gbCopy),edited)
  await button('返回文件中心').click()
  await page.evaluate(()=>{
    window.immediateRichAttempt=new Promise(resolve=>{
      const observer=new MutationObserver(()=>{
        if (!document.querySelector('.md-source-large')) return
        observer.disconnect()
        const rich=[...document.querySelectorAll('.mode-switch button')].find(el=>el.textContent==='富文本')
        rich.click()
        resolve()
      })
      observer.observe(document.body,{childList:true,subtree:true})
    })
  })
  await open(largeFile)
  await page.evaluate(()=>window.immediateRichAttempt)
  const virtual=label('Markdown 源码')
  await virtual.waitFor()
  assert.equal(await virtual.getAttribute('contenteditable'),'true')
  await button('终卷').click()
  await virtual.getByText('# 终卷',{exact:true}).waitFor()
  await virtual.press('Control+h')
  await label('查找文字').fill('原句')
  await label('替换文字').fill('校订')
  await button('全部替换').click()
  await savedBytes(largeFile,Buffer.from(largeRaw.replaceAll('原句','校订')))
  await button('关闭查找').click()
  await virtual.press('Control+z')
  await savedBytes(largeFile,Buffer.from(largeRaw))
  await button('阅读').click()
  const formula=label('Markdown 阅读正文').getByRole('button',{name:/编辑第 .*行公式源码/})
  await page.locator('.md-reading .md-block-slot').first().scrollIntoViewIfNeeded()
  await formula.click()
  const selected=await virtual.evaluate(el=>{
    const data=new DataTransfer()
    el.dispatchEvent(new ClipboardEvent('copy',{bubbles:true,cancelable:true,clipboardData:data}))
    return data.getData('text/plain')
  })
  assert.equal(selected,'x^2 + y^2')
  await page.keyboard.insertText('z^2')
  await savedBytes(largeFile,Buffer.from(largeRaw.replace('x^2 + y^2','z^2')))
  await virtual.press('Control+z')
  await savedBytes(largeFile,Buffer.from(largeRaw))
  assert.deepEqual(errors,[])
  console.log('Windows Electron offline writing checks passed: Markdown writing modes and rendering, TXT format undo, byte-accurate GBK overwrite, original-encoding Save As, cancellation, protected UTF-8 fallback.')
} finally {
  if (app) {
    if(errors.length) console.error(errors)
    // All documents in this process belong to its temporary test profile.
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:1})}).catch(()=>{})
    await app.close().catch(()=>{})
  }
  if (dirname(temp)===resolve(tmpdir()) && basename(temp).startsWith('yanye-writing-ui-')) await rm(temp,{recursive:true,force:true,maxRetries:5})
}
