import assert from 'node:assert/strict'
import { mkdtemp, readFile, rm } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { _electron } from 'playwright'
import { readXlsx } from '../src/modules/spreadsheet-xlsx.js'

const root = resolve(fileURLToPath(new URL('../', import.meta.url)))
const temp = await mkdtemp(join(tmpdir(),'yanye-grid-test-'))
const exe = process.argv[2] ? resolve(process.argv[2]) : createRequire(import.meta.url)('electron')
const output = join(temp,'预算.xlsx')
let app
async function start(firstLaunch = false) {
  app = await _electron.launch({ executablePath:exe, args:process.argv[2] ? [] : [root], env:{...process.env,YANYE_PROFILE:join(temp,'profile')} })
  const page = await app.firstWindow()
  page.setDefaultTimeout(8000)
  if (firstLaunch) await page.getByRole('button',{name:'写作工作台',exact:true}).click()
  await page.getByRole('textbox',{name:'页面标题'}).waitFor()
  return page
}
async function close() {
  const ended = app.waitForEvent('close',{timeout:8000})
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].close()).catch(()=>{})
  await ended
  app = undefined
}
try {
  let page = await start(true)
  await page.getByRole('button',{name:'新建页面',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'电子表格',exact:true}).click()
  const cell = ref=>page.locator('td[data-address="'+ref+'"]')
  async function fill(ref, text) {
    await cell(ref).dblclick()
    const input = page.getByRole('textbox',{name:'编辑 '+ref,exact:true})
    await input.fill(text)
    await input.press('Enter')
  }
  await fill('A1','支出'); await fill('B1','金额')
  await fill('A2','宣传'); await fill('B2','12'); await fill('A3','材料'); await fill('B3','30')
  await fill('B4','=SUM(B2:B3)')
  assert.equal(await cell('B4').innerText(),'42')
  await cell('A1').click()
  await cell('B1').click({modifiers:['Shift']})
  assert.equal(await page.getByLabel('名称框').inputValue(),'A1:B1')
  await page.getByRole('button',{name:'加粗选区'}).click()
  assert.equal(await cell('B1').evaluate(el=>getComputedStyle(el).fontWeight),'700')
  await page.getByLabel('选区水平对齐').selectOption('center')
  await page.getByLabel('选区字体',{exact:true}).selectOption('宋体')
  await page.getByLabel('选区字号').selectOption('18')
  await page.getByText('行与列',{exact:true}).click()
  await page.getByRole('button',{name:'设置选区列宽'}).click()
  await page.getByRole('spinbutton',{name:'列宽（字符）'}).fill('20')
  await page.getByRole('button',{name:'应用列宽'}).click()
  const copied=await page.locator('.sheet-scroll').evaluate(el=>{
    const data=new DataTransfer()
    el.dispatchEvent(new ClipboardEvent('copy',{clipboardData:data,bubbles:true,cancelable:true}))
    return Object.fromEntries(data.types.map(type=>[type,data.getData(type)]))
  })
  assert.equal(copied['text/plain'],'支出\t金额')
  await cell('D1').click()
  await page.locator('.sheet-scroll').evaluate((el,source)=>{
    const data=new DataTransfer()
    for (const [type,value] of Object.entries(source)) data.setData(type,value)
    el.dispatchEvent(new ClipboardEvent('paste',{clipboardData:data,bubbles:true,cancelable:true}))
  },copied)
  assert.equal(await cell('E1').innerText(),'金额')
  assert.equal(await cell('E1').evaluate(el=>getComputedStyle(el).fontWeight),'700')
  await cell('D3').click()
  await page.keyboard.press('Shift+ArrowRight')
  await page.getByRole('button',{name:'合并单元格',exact:true}).click()
  assert.equal(await cell('D3').getAttribute('colspan'),'2')
  await page.getByRole('button',{name:'撤销表格操作'}).click()
  assert.equal(await cell('E3').count(),1)
  await page.getByRole('button',{name:'重做表格操作'}).click()
  assert.equal(await cell('D3').getAttribute('colspan'),'2')
  await cell('F2').click()
  await page.getByText('数据规则',{exact:true}).click()
  await page.getByRole('button',{name:'下拉列表验证'}).click()
  await page.getByLabel('下拉选项').fill('计划，完成')
  await page.getByRole('button',{name:'应用到选区'}).click()
  await page.getByLabel('单元格下拉列表').selectOption('完成')
  assert.equal(await cell('F2').innerText(),'完成')
  await cell('B2').click()
  await cell('B4').click({modifiers:['Shift']})
  await page.getByText('数据规则',{exact:true}).click()
  await page.getByRole('button',{name:'数值条件格式'}).click()
  await page.getByLabel('条件阈值').fill('20')
  await page.getByRole('button',{name:'应用到选区'}).click()
  assert.equal(await cell('B3').evaluate(el=>el.style.backgroundColor),'rgb(255, 220, 134)')
  await cell('A1').click()
  await cell('B3').click({modifiers:['Shift']})
  await page.getByText('排序与筛选',{exact:true}).click()
  await page.getByRole('button',{name:'对选区启用自动筛选'}).click()
  await page.getByLabel('列值筛选').selectOption(JSON.stringify(['宣传']))
  assert.equal(await cell('A3').count(),0)
  await page.getByLabel('列值筛选').selectOption('null')
  await cell('B3').click()
  await page.getByText('排序与筛选',{exact:true}).click()
  await page.getByRole('button',{name:'按 B 列降序'}).click()
  const order = await page.locator('tbody tr th').allTextContents()
  assert.deepEqual(order.slice(0,4),['1','4','3','2'])
  await page.getByRole('button',{name:'柱状图',exact:true}).click()
  await page.getByRole('region',{name:'柱状图'}).waitFor()
  await page.getByLabel('图表配色').selectOption('ocean')
  await page.getByRole('button',{name:'新建工作表'}).click()
  await fill('A1','=工作表1!B4*2')
  assert.equal(await cell('A1').innerText(),'84')
  await app.evaluate(({dialog},file)=>{
    dialog.showSaveDialog = async()=>({canceled:false,filePath:file})
    dialog.showOpenDialog = async()=>({canceled:false,filePaths:[file]})
  },output)
  await page.locator('.sheet-menu summary').filter({hasText:'导出'}).click()
  await page.getByRole('button',{name:'导出 XLSX'}).click()
  await page.getByText('已导出 XLSX。',{exact:false}).waitFor().catch(async error=>{throw new Error(await page.locator('.sheet-info [role=status]').innerText(),{cause:error})})
  const exported = await readXlsx((await readFile(output)).toString('base64'))
  assert.equal(exported.length,2)
  assert.equal(exported[1].cells.A1,'=工作表1!B4*2')
  assert.equal(exported[0].styles.B1.align,'center')
  assert.equal(exported[0].styles.E1.bold,true)
  assert.equal(exported[0].styles.E1.font,'宋体')
  assert.equal(exported[0].styles.E1.size,18)
  assert.equal(exported[0].widths[1],20)
  assert.deepEqual(exported[0].merges,[{top:2,left:3,bottom:2,right:4}])
  assert.equal(exported[0].validations[0].formulae[0],'"计划,完成"')
  assert.equal(exported[0].conditions[0].ref,'B2:B4')
  assert.equal(exported[0].chart.colors[0].toLowerCase(),'#396591')
  await page.locator('.sheet-menu summary').filter({hasText:'导入'}).click()
  await page.getByRole('button',{name:'导入 XLSX'}).click()
  await page.getByText('已添加 2 张工作表。',{exact:false}).waitFor()
  await page.getByRole('button',{name:'工作表2 (2)',exact:true}).click()
  assert.equal(await cell('A1').innerText(),'84')
  await close()
  page = await start()
  assert.equal(await cell('A1').innerText(),'84')
  await close()
  console.log('Windows 网格编辑、排序、柱状图、跨表求和、XLSX 实际导入导出及重启持久化通过。')
} finally {
  if (app) await app.close().catch(()=>{})
  await rm(temp,{recursive:true,force:true,maxRetries:5})
}
