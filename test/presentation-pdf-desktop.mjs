import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { PDFDocument, PDFName } from 'pdf-lib'
import JSZip from 'jszip'
import { _electron } from 'playwright'
import { newSlide, slideShape } from '../src/modules/slides-model.js'
import { exportPptx } from '../src/modules/slides-pptx.js'

const root=resolve(fileURLToPath(new URL('../',import.meta.url))), temp=await mkdtemp(join(tmpdir(),'yanye-presentation-pdf-'))
const fixtures=process.env.YANYE_PRESENTATION_FIXTURES || temp
const pdf=join(fixtures,'source.pdf'), ppt=join(fixtures,'source.pptx'), outPdf=join(fixtures,'result.pdf'), outPpt=join(fixtures,'result.pptx')
const exe=process.argv[2]?resolve(process.argv[2]):createRequire(import.meta.url)('electron')
let app, window
try {
  if (fixtures===temp) {
    const geometry=slideShape({kind:'diamond',text:'流程起点',fill:'A2B3C4',stroke:'204966'})
    const data=await exportPptx({theme:'paper',slides:[newSlide({title:'评审',shapes:[geometry]})]},'评审')
    await writeFile(ppt,Buffer.from(data,'base64'))
    const file=await PDFDocument.create()
    for (const n of [1,2,3]) file.addPage([400,500]).drawText('Page '+n,{x:50,y:400})
    await writeFile(pdf,await file.save())
  }
  const original=await readFile(pdf)
  app=await _electron.launch({executablePath:exe,args:process.argv[2]?[]:[root],env:{...process.env,YANYE_PROFILE:join(temp,'profile')},timeout:22000})
  window=await app.firstWindow({timeout:12000})
  window.setDefaultTimeout(12000)
  await window.context().setOffline(true)
  const errors=[]
  window.on('pageerror',e=>errors.push(e.message))
  const button=name=>window.getByRole('button',{name,exact:true}), label=name=>window.getByLabel(name,{exact:true})
  const dialog=path=>app.evaluate(({dialog},path)=>{
    dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]})
    dialog.showSaveDialog=async()=>({canceled:false,filePath:path})
    dialog.showMessageBox=async()=>({response:1})
  },path)
  await dialog(ppt)
  await button('打开本地文件').click()
  await button('切换').click()
  if (fixtures!==temp) {
    assert.equal(await label('切换效果').inputValue(),'fade')
    assert.equal(await label('停留秒数').inputValue(),'3')
  }
  await label('切换效果').selectOption('cut')
  await label('定时换页').check()
  await label('停留秒数').fill('0.5')
  await label('停留秒数').press('Enter')
  await button('关闭切换设置').click()
  if (fixtures!==temp) {
    await button('放映').click()
    await window.getByText('2 / 3',{exact:true}).waitFor()
    await window.keyboard.press('Escape')
    await window.getByRole('button',{name:/^第 1 页 /}).click()
  }
  await button('选择形状 流程起点').click()
  if (fixtures!==temp) assert.equal(await label('幻灯片标题').inputValue(),'','a shapes-only slide has no inferred text title')
  assert.equal(await label('形状填充').inputValue(),'#a2b3c4')
  assert.equal(await label('形状轮廓').inputValue(),'#204966')
  await label('形状文字').fill('复核通过')
  await label('形状旋转').fill('30')
  await label('形状旋转').press('Enter')
  await label('形状类型').selectOption('rightArrow')
  await button('插入形状').click()
  await label('形状文字').fill('下一步')
  await button('插入文本框').click()
  await label('文本框 1').fill('结项说明')
  await label('文本框字体').selectOption('Georgia')
  await button('加粗').click()
  await label('文本框对齐').selectOption('right')
  await dialog(outPpt)
  await button('另存为').click()
  await button('result.pptx').first().waitFor()
  const zip=await JSZip.loadAsync(await readFile(outPpt))
  const slide=await zip.file('ppt/slides/slide1.xml').async('string')
  for(const term of ['复核通过','prst="rightArrow"','下一步','Georgia','结项说明']) assert.ok(slide.includes(term),term)
  assert.equal(slide.match(/>复核通过</g)?.length,1)
  await button('返回文件中心').click()
  await dialog(pdf)
  await button('打开本地文件').click()
  await window.locator('.pdf-scroll canvas[data-rendered]').waitFor()
  await button('整理与批注').click()
  await button('下一页').click()
  const textLayer=window.locator('.pdf-scroll .pdf-text').getByText('Page 2',{exact:true})
  await textLayer.waitFor()
  await textLayer.evaluate(el=>{
    const selection=window.getSelection(), range=document.createRange()
    range.selectNodeContents(el);selection.removeAllRanges();selection.addRange(range)
  })
  await button('高亮选区').click()
  await window.locator('.pdf-scroll .pdf-mark').first().waitFor()
  await button('右旋').click()
  await button('前移').click()
  await window.locator('.pdf-scroll canvas[data-page="2"][data-rendered]').waitFor()
  await button('添加便签').click()
  await label('PDF 便签内容').fill('第二页核对')
  await window.locator('.pdf-scroll .pdf-paper').click({position:{x:70,y:60}})
  await label('本页便签').getByText('第二页核对',{exact:false}).waitFor()
  await button('转到第 3 页').click()
  await button('移除本页').click()
  await window.getByText('共 2 页',{exact:true}).waitFor()
  const extra=join(temp,'appendix.pdf'), extract=join(temp,'extract.pdf'), merge=join(temp,'merge.pdf')
  const appendix=await PDFDocument.create()
  appendix.addPage([210,310]).drawText('Appendix A')
  appendix.addPage([310,410]).drawText('Appendix B')
  const appendixBytes=Buffer.from(await appendix.save())
  await writeFile(extra,appendixBytes)
  await label('提取页码范围').fill('9')
  await button('提取为 PDF').click()
  await window.getByRole('alert').filter({hasText:'页码范围无效'}).waitFor()
  await label('提取页码范围').fill('1')
  await app.evaluate(({dialog})=>{dialog.showSaveDialog=async()=>({canceled:true});dialog.showOpenDialog=async()=>({canceled:true,filePaths:[]})})
  await button('提取为 PDF').click()
  await window.getByText('正在准备副本…',{exact:true}).waitFor({state:'hidden'})
  await button('追加另一份 PDF 并导出').click()
  await window.getByText('正在准备副本…',{exact:true}).waitFor({state:'hidden'})
  await dialog(extract)
  await button('提取为 PDF').click()
  await window.getByText('已导出 extract.pdf',{exact:true}).waitFor()
  const selected=await PDFDocument.load(await readFile(extract))
  assert.equal(selected.getPageCount(),1)
  assert.equal(selected.getPage(0).getRotation().angle,90)
  assert.equal(selected.getPage(0).node.Annots().size(),2)
  await app.evaluate(({dialog},files)=>{
    dialog.showOpenDialog=async()=>({canceled:false,filePaths:[files.extra]})
    dialog.showSaveDialog=async()=>({canceled:false,filePath:files.merge})
  },{extra,merge})
  await button('追加另一份 PDF 并导出').click()
  await window.getByText('已导出 merge.pdf',{exact:true}).waitFor()
  const merged=await PDFDocument.load(await readFile(merge))
  assert.equal(merged.getPageCount(),4)
  assert.equal(merged.getPage(0).node.Annots().size(),2)
  assert.deepEqual(merged.getPages().slice(-2).map(p=>p.getWidth()),[210,310])
  assert.deepEqual(await readFile(extra),appendixBytes)
  await dialog(outPdf)
  await window.keyboard.press('Control+s')
  await button('result.pdf').first().waitFor()
  await window.locator('.pdf-scroll canvas[data-rendered]').waitFor()
  if ((await button('整理与批注').getAttribute('aria-expanded'))!=='true') await button('整理与批注').click()
  await button('便签 第二页核对').waitFor()
  assert.deepEqual(await readFile(pdf),original)
  const output=await PDFDocument.load(await readFile(outPdf))
  assert.equal(output.getPageCount(),2)
  const first=output.getPage(0)
  assert.equal(first.getRotation().angle,90)
  const annotations=first.node.Annots().asArray().map(ref=>output.context.lookup(ref))
  assert.ok(annotations.some(a=>a.get(PDFName.of('Contents'))?.decodeText()==='第二页核对'))
  assert.ok(annotations.some(a=>a.get(PDFName.of('Subtype'))?.toString()==='/Highlight' && a.get(PDFName.of('QuadPoints'))?.size()>=8))
  assert.deepEqual(errors,[])
  console.log('Electron offline: native shapes, PDF organize/notes/highlights, extract/append, invalid range and cancellation, source-safe Ctrl+S and independent re-open passed.')
} catch(e) {
  console.error(await window?.locator('body').innerText().catch(()=>''));throw e
} finally {
  if(app)await app.close().catch(()=>{})
  await rm(temp,{recursive:true,force:true,maxRetries:4})
}
